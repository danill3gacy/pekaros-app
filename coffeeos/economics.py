"""Уровень сервиса витрины: насколько ставить больше среднего спроса.

Здесь живёт ответ на главный вопрос заказа витрины: НАСКОЛЬКО брать больше
среднего спроса. Непроданный круассан и круассан, которого не хватило, стоят
по-разному: первый — остаток, второй — гость, который взял только кофе.

И в кофейне эта разница резче, чем где-либо ещё. Не хватило булки в пекарне —
потеряли продажу булки. Не хватило еды к кофе — потеряли не только еду: гость,
который брал кофе с круассаном каждое утро, начинает брать завтрак там, где он
есть, и кофе тоже начинает брать там. Витрина держит средний чек, поэтому
пустая витрина стоит дороже, чем списанный остаток.

Потери несимметричны, поэтому выгодный заказ — не средний спрос, а его верхний
перцентиль (классическая задача о газетчике, newsvendor).

Уровень сервиса берётся из настройки CASE_SERVICE_LEVEL. Себестоимость витрины
в этот расчёт НЕ входит: она нужна для маржи, но не для выбора размера партии —
для него достаточно спроса и его разброса.
"""

from statistics import NormalDist

from . import config

# Границы уровня сервиса.
#   Нижняя — медиана: ниже неё обратная связь ломается (взяли меньше →
#   чаще распродались → оценили спрос ещё ниже → взяли ещё меньше).
#   Верхняя — 0.90: выше заказ определяется хвостом распределения, а хвост
#   по нескольким наблюдениям не оценить.
MIN_SERVICE = 0.50
MAX_SERVICE = 0.90

_ND = NormalDist()


def service_level():
    """Целевой уровень сервиса витрины (перцентиль спроса)."""
    return min(MAX_SERVICE, max(MIN_SERVICE, config.CASE_SERVICE_LEVEL))


def z_for(sl):
    """Сколько сигм прибавить к среднему спросу, чтобы попасть в уровень сервиса."""
    sl = min(0.999, max(0.001, sl))
    return _ND.inv_cdf(sl)


def plan_z():
    """Готовый коэффициент для заказа витрины.

    Считается на каждый вызов, а не один раз при импорте модуля: уровень
    сервиса задаётся в .env, и закэшированное на старте значение делало
    настройку неработающей.
    """
    sl = service_level()
    return {"service_level": sl, "z": z_for(sl)}
