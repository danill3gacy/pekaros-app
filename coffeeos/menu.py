NOT_SERVICE_HINTS = ["тесте", "тесто", "тестов", "упаковке"]


def is_service_item(name):
    """Служебная позиция кассы (пакет, скидка, депозит), а не товар кофейни.

    Исключение снимает подозрение ТОЧЕЧНО — только если сработавшая подсказка
    попала внутрь слова-исключения. Иначе «Скидка на тесто» считалась товаром.
    """
    low = (name or "").lower()
    for h in NON_PRODUCT_HINTS:
        pos = low.find(h)
        if pos < 0:
            continue
        covered = False
        for ex in NOT_SERVICE_HINTS:
            start = low.find(ex)
            if start >= 0 and start <= pos < start + len(ex):
                covered = True
                break
        if not covered:
            return True
    return False


def _is_addon(low):
    return any(re.search(p, low) for p in ADDON_WHOLE)


def _find_drink(low):
    """Найти напиток по синониму. Возвращает строку словаря DRINKS либо None."""
    for alias, row in _DRINK_LOOKUP:
        # Границы слова важны: «чай» не должен ловиться в «чайник», а «раф» —
        # в «графин». Кириллицу \b в Python обрабатывает корректно.
        if re.search(r"(?<![а-яёa-z])" + re.escape(alias) + r"(?![а-яёa-z])", low):
            return row
    return None


def parse(name):
    """Разобрать позицию чека.

    Возвращает словарь: base, kind, category, size, volume_ml, milk, iced, mods.
    Ничего не выдумывает: неизвестный размер остаётся None, неизвестное
    молоко — None. Продукт потом честно скажет, чего нет в выгрузке.
    """
    raw = (name or "").strip()
    low = raw.lower()
    empty = {"base": raw, "kind": KIND_UNKNOWN, "category": CAT_OTHER,
             "size": None, "volume_ml": None, "milk": None, "iced": 0, "mods": ""}
    if not raw:
        return empty

    # Порядок проверок существенный. Товар обязан проверяться РАНЬШЕ напитка:
    # «Кофе в зёрнах 250 г» — это пачка на полке, и если счесть её напитком,
    # система спишет на неё 18 г зерна и добавит несуществующую чашку в
    # расчёт загрузки бариста.
    if is_service_item(raw):
        return {**empty, "kind": KIND_SERVICE, "category": CAT_OTHER}

    if _is_addon(low):
        milk = next((n for n, hints in MILK_TYPES if any(h in low for h in hints)), None)
        return {**empty, "base": _addon_base(raw, low), "kind": KIND_ADDON,
                "category": CAT_ADDON, "milk": milk, "mods": _mods_of(low)}

    if any(h in low for h in GOODS_HINTS):
        return {**empty, "kind": KIND_GOODS, "category": CAT_GOODS}

    drink = _find_drink(low)
    if drink is not None:
        base, _aliases, _shots, milk_at_m, coffee = drink
        volume = _volume_ml(low)
        size = _size_letter(low, volume)
        iced = 1 if (base in _ALWAYS_ICED or any(h in low for h in _ICED_HINTS)) else 0
        return {"base": base, "kind": KIND_DRINK,
                "category": CAT_COFFEE if coffee else CAT_DRINKS,
                "size": size, "volume_ml": volume,
                "milk": _milk_of(low, milk_at_m), "iced": iced, "mods": _mods_of(low)}

    if any(h in low for h in FOOD_HINTS):
        return {**empty, "base": _food_base(raw), "kind": KIND_FOOD, "category": CAT_FOOD}
    return empty


def _addon_base(raw, low):
    """Имя добавки без вкуса: «Сироп карамель» и «Сироп ваниль» — один расход."""
    if "сироп" in low:
        return "Сироп"
    if re.search(r"молоко|молок", low):
        milk = next((n for n, hints in MILK_TYPES if any(h in low for h in hints)), None)
        return f"Молоко {milk}" if milk else "Молоко"
    return raw.strip()


def _food_base(raw):
    """Витрина остаётся под своим именем: «Круассан миндальный» — своя позиция
    со своим спросом, схлопывать её с классическим круассаном нельзя."""
    return re.sub(r"\s+", " ", raw).strip()


def _mods_of(low):
    out = []
    for tag, pats in MOD_PATTERNS:
        if any(re.search(p, low) for p in pats):
            out.append(tag)
    return ";".join(out)


_VOWEL_TAIL = "аеёиоуыэюяйьъ"


def stem(word):
    """Грубая основа слова: отсекаем падежное окончание.

    Полноценный стеммер здесь не нужен и вреден — он тянет зависимость ради
    сопоставления пары десятков названий. Достаточно снять до двух гласных с
    конца, оставив минимум две буквы: «калибровку» -> «калибровк»,
    «картриджа» -> «картридж», «рафа» -> «раф».
    """
    w = (word or "").lower()
    for _ in range(2):
        if len(w) > 2 and w[-1] in _VOWEL_TAIL:
            w = w[:-1]
        else:
            break
    return w


def size_or_default(size):
    """Размер для расчёта рецепта, когда касса его не отдаёт.

    Возвращает (размер, известен_ли). Второе значение обязано доезжать до
    интерфейса: «средний размер» вместо реального — это допущение, и владелец
    должен знать, что оно сделано.
    """
    return (size, True) if size in SIZE_DEFAULT_ML else ("M", False)


def milk_or_default(milk, base):
    """Молоко для расчёта рецепта. Для напитка, где молока нет, — None."""
    row = DRINK_BY_NAME.get(base)
    if row is not None and not row[3]:
        return None, True
    if milk:
        return milk, True
    return MILK_REGULAR, False


def is_coffee(base):
    row = DRINK_BY_NAME.get(base)
    return bool(row and row[4])


def espresso_shots(base):
    row = DRINK_BY_NAME.get(base)
    return row[2] if row else 0


def milk_ml(base, size):
    """Сколько молока в напитке этого размера, мл."""
    row = DRINK_BY_NAME.get(base)
    if not row or not row[3]:
        return 0
    at_m = row[3]
    factor = {"S": 0.7, "M": 1.0, "L": 1.35}.get(size or "M", 1.0)
    return round(at_m * factor)
