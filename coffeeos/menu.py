# ---------- размер и объём ----------
# Кофейни в РФ работают в основном на 250 / 350 / 450 мл. Границы взяты так,
# чтобы 200-мл капучино попал в S, а 400-мл латте — в L.
SIZE_BOUNDS = ((280, "S"), (380, "M"))          # <=280 -> S, <=380 -> M, иначе L
SIZE_DEFAULT_ML = {"S": 250, "M": 350, "L": 450}

_SIZE_WORDS = [
    (r"\b(?:xl|хl)\b", "L"), (r"\bбольшой\b|\bбольшая\b|\bбольшое\b|\blarge\b|\bбол\.", "L"),
    (r"\bсредний\b|\bсредняя\b|\bсреднее\b|\bmedium\b|\bср\.", "M"),
    (r"\bмаленький\b|\bмаленькая\b|\bмаленькое\b|\bsmall\b|\bмал\.", "S"),
]


def _volume_ml(low):
    """Объём в мл из названия: «300 мл», «0,4 л», «0.3л», «450»."""
    m = re.search(r"(\d+(?:[.,]\d+)?)\s*(?:мл|ml)\b", low)
    if m:
        return int(round(float(m.group(1).replace(",", "."))))
    m = re.search(r"(\d(?:[.,]\d+)?)\s*(?:л|l)\b", low)
    if m:
        val = float(m.group(1).replace(",", "."))
        if 0.1 <= val <= 2.0:
            return int(round(val * 1000))
    # «Латте 0,3» и «Латте 0,35» — литры без единицы измерения, частая запись в кассе
    m = re.search(r"(?<!\d)0[.,](\d{1,2})(?!\d)", low)
    if m:
        return int(round(float("0." + m.group(1)) * 1000))
    # голое число рядом с напитком: «Латте 400», «Капучино 250»
    m = re.search(r"(?<!\d)(150|180|200|230|250|260|280|300|330|350|360|400|420|450|470|500)(?!\d)", low)
    if m:
        return int(m.group(1))
    return None


def _size_letter(low, volume):
    """Размер: сначала явная буква/слово, затем — из объёма."""
    if re.search(r"(?:^|[\s,(/])s(?:$|[\s,)/.])", low):
        return "S"
    if re.search(r"(?:^|[\s,(/])m(?:$|[\s,)/.])", low):
        return "M"
    if re.search(r"(?:^|[\s,(/])l(?:$|[\s,)/.])", low):
        return "L"
    for pat, letter in _SIZE_WORDS:
        if re.search(pat, low):
            return letter
    if volume:
        for bound, letter in SIZE_BOUNDS:
            if volume <= bound:
                return letter
        return "L"
    return None


