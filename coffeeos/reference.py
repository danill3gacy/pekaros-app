def ensure_loaded(conn):
    """Наполнить справочники один раз. Правки владельца не затирает.

    Флаг в kv, а не проверка «пусто ли»: если владелец осознанно удалил
    ненужный ему ингредиент (соевое молоко, которое он не продаёт), тот не
    должен возвращаться при каждом запуске.
    """
    if _db.kv_get(conn, "reference_loaded") == REFERENCE_VERSION:
        return False
    for name, unit, pack_qty, price, pack_name, cat, shelf, lead, min_packs in INGREDIENTS:
        conn.execute(
            "INSERT OR IGNORE INTO ingredients"
            "(name,unit,pack_qty,pack_price,pack_name,category,shelf_days,lead_days,min_packs,price_src)"
            " VALUES(?,?,?,?,?,?,?,?,?,'default')",
            (name, unit, pack_qty, price, pack_name, cat, shelf, lead, min_packs),
        )
    for item, size, ingredient, qty in build_recipes():
        conn.execute(
            "INSERT OR IGNORE INTO recipes(item,size,ingredient,qty,src) VALUES(?,?,?,?,'default')",
            (item, size, ingredient, qty),
        )
    for task, period, note in MAINTENANCE:
        conn.execute(
            "INSERT OR IGNORE INTO maintenance(task,period_days,note) VALUES(?,?,?)",
            (task, period, note),
        )
    _db.kv_set(conn, "reference_loaded", REFERENCE_VERSION)
    conn.commit()
    return True


def build_recipes():
    """Развернуть рецептуру в строки (позиция, размер, ингредиент, кол-во).

    Размеры разворачиваются явно, а не считаются на лету: владелец должен иметь
    возможность открыть рецепт латте размера L и поправить в нём одно число,
    не трогая остальные.
    """
    out = []
    for base, _aliases, _shots, milk_at_m, _coffee in menu.DRINKS:
        for size in ("S", "M", "L"):
            factor = SIZE_FACTOR[size]
            parts = {}
            g = COFFEE_G.get(base, 0)
            if g:
                if size == "L" and base not in NO_EXTRA_SHOT:
                    g += EXTRA_SHOT_G
                parts["Зерно кофе"] = g
            if milk_at_m:
                # молоко по умолчанию обычное; подмена на альтернативное
                # делается при расчёте, по данным чека
                parts["Молоко обычное"] = round(milk_at_m * factor)
            for ing, qty in DRINK_EXTRAS.get(base, {}).items():
                parts[ing] = round(qty * factor, 2)
            parts[CUP_BY_SIZE[size]] = 1
            parts["Крышка"] = 1
            parts["Прочие расходники"] = 1
            for ing, qty in parts.items():
                out.append((base, size, ing, qty))
    return out
